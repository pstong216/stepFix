def cmd_fix(a):
    """kept corrections (textcraft_round.py select output) -> training rows: plan SFT (the teacher's corrected plan, regenerated with the
    verified action forced as Next when the teacher's plan named another action) + one-hot KL on the verified action conditioned on that plan.
    Rows read virtual episodes (<out_dir>/train_episodes.jsonl): the student's episode with steps[t].plan replaced by the corrected plan."""
    from textcraft_round import merge
    D = ROOT / a.out_dir; eps = {e["id"]: e for e in L(ROOT / a.traj)}
    tg = merge(sorted(glob.glob(str(D / "targets_s*.jsonl"))), lambda r: (r["id"], r["t"])); diag = {r["id"]: r for r in L(D / "diag_modelA.raw.jsonl")}
    kept = L(D / "targets_env_top_margin" / "train.jsonl"); need = [r for r in kept if plan_next(tg[(r["id"], r["t"])]["corr_plan"]) != r["cand"]]
    print(f"{len(kept)} kept corrections; teacher plan names a different Next than the verified action in {len(need)} -> regenerated with the verified action forced", flush=True)
    regen = {}
    if need:
        tok, model, pol = load_policy(a.model, str(ROOT / a.adapter) if not os.path.isabs(a.adapter) else a.adapter); model.eval()
        for r in need:
            T = tg[(r["id"], r["t"])]; fv = FullView(eps[r["id"]], r["t"], diag_line(diag.get(r["id"])))
            p = generate_batch(tok, model, [chat(tok, PLAN_SYSTEM, fv.plan_prompt(T["analysis"], forced_next=r["cand"]))], a.plan_tokens, 0.0)[0]
            if plan_next(p) != r["cand"]: p = re.sub(r"Next:\s*.+$", f"Next: {r['cand']}.", p) if "Next:" in p else p.rstrip(". ") + f". Next: {r['cand']}."
            regen[(r["id"], r["t"])] = set_have(p, fv.inv) if ENV_INV else p
    vfile = D / "train_episodes.jsonl"; rows = []; n_follow = 0
    with open(vfile, "w") as fv_:
        for r in kept:
            key = (r["id"], r["t"]); T = tg[key]; plan = regen.get(key, T["corr_plan"]); n_follow += key not in regen
            e = json.loads(json.dumps(eps[r["id"]])); e["id"] = f"{r['id']}__c{r['t']}"; e["steps"][r["t"]]["plan"] = plan; fv_.write(json.dumps(e) + "\n")
            src = str(vfile.relative_to(ROOT))
            rows.append({"kind": "sft", "src": src, "id": e["id"], "t": -r["t"] - 1, "action": plan, "role": "corr_plan"})
            rows.append({"kind": "kl", "src": src, "id": e["id"], "t": r["t"], "cmds": r["cmds"], "target": r["target"], "cand": r["cand"], "role": "corr_action"})
    open(D / "train_corrections.jsonl", "w").writelines(json.dumps(x) + "\n" for x in rows)
    print(f"correction rows: {len(rows)} ({len(kept)} plan SFT + {len(kept)} action KL); teacher plan kept as is for {n_follow}, regenerated for {len(regen)}")


def cmd_replay(a):
    rows = L(ROOT / a.replay); eps = {e["id"]: e for e in L(ROOT / a.traj)}; out = []
    for r in rows:
        e = eps[r["id"]]; out.append({"kind": "sft", "src": r["src"], "id": r["id"], "t": -r["t"] - 1, "action": e["steps"][r["t"]]["plan"], "role": "replay_plan"})
        out.append(dict(r, role="replay_action"))
    open(ROOT / a.out, "w").writelines(json.dumps(x) + "\n" for x in out)
    print(f"replay: {len(rows)} steps -> {len(out)} rows (plan SFT + action SFT per step, the student's own plans)")


