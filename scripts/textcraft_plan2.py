class FullView:
    """task + the WHOLE failed trajectory (full prefix with plans, every remaining step with its plan and full observation) + outcome
    (+ the environment's current inventory when ENV_INV)."""
    def __init__(self, e, t, diag_line):
        self.e, self.t = e, t; self.adm = e["steps"][t]["admissible"]; self.steps = [_Step(self.adm)]
        self.inv = true_inventory(e, t)
        self.diag = ((f"Current inventory (from the environment): {self.inv}.\n" if ENV_INV else "") + diag_line).strip()
        self.block = "\n".join(f"- step {t + i}: plan: {s['plan']} | action: {s['action']} -> {s['next_obs']}" for i, s in enumerate(e["steps"][t:]))
    def core(self, extra=""):
        e, t = self.e, self.t
        base = render(e["initial_obs"], past_of(e, t), self.adm, None, history=10 ** 9).rsplit(PLAN_ASK, 1)[0].rstrip() + "\n"
        note = ("Hindsight: this attempt FAILED (the goal item was never crafted). After this point the agent did the following "
                f"(episode length {len(e['steps'])} steps, step budget {e['budget']}, budget exhausted):\n{self.block}\n"
                "Using everything above, choose the best action for the CURRENT step.\n" + (self.diag + "\n" if self.diag else "") + extra)
        return base.replace("Admissible actions:", note + "Admissible actions:", 1)
    def analysis_prompt(self): return self.core() + "\n" + ANALYSIS_Q
    def plan_prompt(self, analysis, forced_next=None):
        ask = PLAN_ASK if not forced_next else f"{PLAN_ASK} The best next action is '{forced_next}', so the plan must end with 'Next: {forced_next}.'"
        return self.core(f"Analysis: {analysis}\n") + "\n" + ask + "\nPlan:"


class ScoreView:
    def __init__(self, fv, analysis, plan): self.fv, self.analysis, self.plan = fv, analysis, plan; self.steps = fv.steps
    def render_prompt(self, max_history_steps=None): return self.fv.core(f"Analysis: {self.analysis}\n") + f"\nPlan: {self.plan}\nNext action:"


def diag_line(d):
    from textcraft_round import TYPE_WORDS
    if not d: return ""
    typ = d.get("type")
    return (f"Diagnosis (an error attributor trained on this agent's own trajectories): the first decisive error was at step {d['t_hat']}"
            + (f", type: {typ} ({TYPE_WORDS.get(typ, typ)})" if typ else "") + ".")


def cmd_teacher(a):
    import torch
    D = ROOT / a.out_dir; eps = {e["id"]: e for e in L(ROOT / a.traj)}
    steps = [(r["id"], r["steps"][0]) for r in L(D / "pointer.jsonl")]; diag = {r["id"]: r for r in L(D / "diag_modelA.raw.jsonl")}
    steps = steps[a.shard[0]::a.shard[1]]                                     # shard BEFORE the resume filter
    out = D / f"targets_s{a.shard[0]}.jsonl"; done = set()
    if out.exists():
        keep = []; own = set(steps)
        for l in open(out):
            try: r = json.loads(l)
            except Exception: continue
            k = (r["id"], r["t"])
            if k in own and k not in done: done.add(k); keep.append(json.dumps(r) + "\n")
        open(out, "w").writelines(keep)
    todo = [s for s in steps if s not in done]; print(f"shard {a.shard}: {len(steps)} states, {len(done)} done, {len(todo)} to do", flush=True)
    tok, model, pol = load_policy(a.model, str(ROOT / a.adapter) if not os.path.isabs(a.adapter) else a.adapter); model.eval()
    t0 = time.time()
    with open(out, "a") as f, torch.no_grad():
        for b0 in range(0, len(todo), a.gen_batch):   # analysis and corrected plan generated for a batch of states at once (greedy)
            chunk = todo[b0: b0 + a.gen_batch]; fvs = [FullView(eps[i], t, diag_line(diag.get(i))) for i, t in chunk]
            ans = generate_batch(tok, model, [chat(tok, GEN_SYSTEM, fv.analysis_prompt()) for fv in fvs], a.analysis_tokens, 0.0, one_line=False)
            cps = generate_batch(tok, model, [chat(tok, PLAN_SYSTEM, fv.plan_prompt(an)) for fv, an in zip(fvs, ans)], a.plan_tokens, 0.0)
            if ENV_INV: cps = [set_have(cp, fv.inv) for fv, cp in zip(fvs, cps)]
            for (i, t), fv, an, cp in zip(chunk, fvs, ans, cps):
                e = eps[i]; lp_plain = pol.score_admissible_commands_cached(history_at(e, t)); lp = pol.score_admissible_commands_cached(ScoreView(fv, an, cp))
                f.write(json.dumps({"id": i, "t": t, "a_minus": e["steps"][t]["action"], "admissible": list(lp), "teacher_logprobs": lp, "plain_logprobs": lp_plain,
                                    "mode": "informed_plan2", "analysis": an, "corr_plan": cp, "student_plan": e["steps"][t]["plan"], "diag": diag.get(i)}) + "\n"); f.flush()
            print(f"[{b0 + len(chunk)}/{len(todo)}] {time.time() - t0:.0f}s", flush=True)
    print("DONE informed_teacher", flush=True)


