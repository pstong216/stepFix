def cmd_sft(a):
    import torch
    from torch.utils.data import Dataset
    from transformers import AutoModelForCausalLM, AutoTokenizer, Trainer, TrainingArguments
    from peft import LoraConfig, get_peft_model
    rng = random.Random(a.seed); eps = [e for e in L(ROOT / a.traj) if e["won"]][: a.n_demos]; pairs = []
    for e in eps:
        for t, s in enumerate(e["steps"]):
            pairs.append((history_at(e, -t - 1, a.history).render_prompt(), s["plan"])); pairs.append((history_at(e, t, a.history).render_prompt(), s["action"]))
    rng.shuffle(pairs); print(f"{len(eps)} demos, {len(pairs)} pairs ({len(pairs) // 2} plan + {len(pairs) // 2} action)", flush=True)
    tok = AutoTokenizer.from_pretrained(a.model); tok.pad_token = tok.pad_token or tok.eos_token

    class DS(Dataset):
        def __init__(self):
            self.items = []
            for u, tgt in pairs:
                p = tok(chat(tok, PLAN_SYSTEM, u), add_special_tokens=False).input_ids; t = tok(tgt, add_special_tokens=False).input_ids + [tok.eos_token_id]
                self.items.append(((p + t)[-a.max_len:], ([-100] * len(p) + t)[-a.max_len:]))
            print(f"max prompt+target length {max(len(x[0]) for x in self.items)} tokens", flush=True)
        def __len__(self): return len(self.items)
        def __getitem__(self, i): return {"input_ids": self.items[i][0], "labels": self.items[i][1]}

    def collate(b):
        m = max(len(x["input_ids"]) for x in b); pad = tok.pad_token_id
        return {"input_ids": torch.tensor([x["input_ids"] + [pad] * (m - len(x["input_ids"])) for x in b]),
                "labels": torch.tensor([x["labels"] + [-100] * (m - len(x["labels"])) for x in b]),
                "attention_mask": torch.tensor([[1] * len(x["input_ids"]) + [0] * (m - len(x["input_ids"])) for x in b])}
    model = AutoModelForCausalLM.from_pretrained(a.model, dtype=torch.bfloat16, device_map={"": 0})
    model.gradient_checkpointing_enable(); model.enable_input_require_grads()
    model = get_peft_model(model, LoraConfig(r=32, lora_alpha=64, lora_dropout=0.05, task_type="CAUSAL_LM",
                                             target_modules=["q_proj", "k_proj", "v_proj", "o_proj", "gate_proj", "up_proj", "down_proj"]))
    args = TrainingArguments(output_dir=str(ROOT / a.out), per_device_train_batch_size=a.bs, gradient_accumulation_steps=a.grad_accum, num_train_epochs=a.epochs,
                             learning_rate=a.lr, lr_scheduler_type="cosine", warmup_steps=20, logging_steps=10, save_strategy="no", bf16=True, report_to=[],
                             remove_unused_columns=False, seed=a.seed)
    Trainer(model=model, args=args, train_dataset=DS(), data_collator=collate).train()
    model.save_pretrained(str(ROOT / a.out / "final")); tok.save_pretrained(str(ROOT / a.out / "final")); print("SAVED", flush=True)


# ----------------------------------------------------------------------------- batched collect
def to_release(ep):
    traj = [{"kind": "user", "content": ep["initial_obs"]}]
    for k, s in enumerate(ep["steps"]):
        traj.append({"kind": "action", "step_number": k + 1, "reasoning": s["plan"], "action": s["action"], "observation": s["next_obs"], "is_final_answer": False})
    return {"id": ep["id"], "framework": "alfagent", "benchmark": "textcraft", "modality": "text", "task": {"query": ep["initial_obs"] + "\n\n" + HINT, "answer": ""},
            "trajectory": traj, "ground_truth": {}, "extras": {"agents": [{"id": "agent", "role": "agent"}]}}


def cmd_collect(a):
    import torch
    torch.manual_seed(a.seed); random.seed(a.seed)
    tasks = splits()[a.split][a.offset:]; tasks = tasks[: a.n] if a.n else tasks           # shard BEFORE the resume filter
    out = ROOT / a.out; out.parent.mkdir(parents=True, exist_ok=True); done = set()
    if out.exists():   # tolerate a truncated last line
        keep = []
        for l in open(out):
            try: r = json.loads(l)
            except Exception: continue
            if r["task"] not in done: done.add(r["task"]); keep.append(json.dumps(r) + "\n")
        open(out, "w").writelines(keep)
    todo = [t for t in tasks if t not in done]; print(f"split {a.split}: {len(tasks)} tasks, {len(done)} done, {len(todo)} to do (batch {a.batch})", flush=True)
    tok, model, pol = load_policy(a.model, a.adapter, merge=True)
    rel = open(str(out).replace(".jsonl", ".release.jsonl"), "a"); t0 = time.time(); n = wins = 0; active = []; tgen = tsc = 0.0; nsteps = 0
    with open(out, "a") as f:
        while todo or active:
            while todo and len(active) < a.batch:
                tid = todo.pop(0); env = TextCraftEnv(); obs0 = env.reset(tid); gold = env.expert_actions()
                active.append({"tid": tid, "env": env, "obs0": obs0, "gold": gold, "B": a.budget or budget_for(len(gold)), "past": [], "steps": [], "obs": obs0, "won": False})
            adms = [x["env"].admissible() for x in active]
            tg = time.time()
            plans = generate_batch(tok, model, [chat(tok, PLAN_SYSTEM, render(x["obs0"], x["past"], adm, None, a.history)) for x, adm in zip(active, adms)], a.plan_tokens, a.plan_temperature)
            tgen += time.time() - tg; ts = time.time(); still = []
            for x, adm, plan in zip(active, adms, plans):
                lp = pol.score_admissible_commands_cached(StepHistory(x["obs0"], x["past"], adm, plan, a.history)); cmds = list(lp)
                if a.temperature <= 0: act = max(cmds, key=lambda c: lp[c])
                else:
                    p = torch.softmax(torch.tensor([lp[c] for c in cmds]) / a.temperature, 0); act = cmds[torch.multinomial(p, 1).item()]
                nxt, r, d = x["env"].step(act); z = torch.logsumexp(torch.tensor(list(lp.values())), 0).item()
                x["steps"].append({"obs": x["obs"], "admissible": adm, "plan": plan, "action": act, "next_obs": nxt, "reward": r, "p_action": round(math.exp(lp[act] - z), 4)})
                x["past"].append((plan, act, nxt)); x["obs"] = nxt; nsteps += 1
                if d: x["won"] = True
                if d or len(x["steps"]) >= x["B"]:
                    env = x["env"]
                    ep = {"id": f"tc_{a.tag}_{a.split}_{x['tid']}", "task": x["tid"], "split": a.split, "goal": item_id_to_str(env.goal), "depth": tree().get_min_depth(env.goal),
                          "initial_obs": x["obs0"], "steps": x["steps"], "won": x["won"], "n_steps": len(x["steps"]), "budget": x["B"], "expert_len": len(x["gold"]),
                          "temperature": a.temperature, "plan_temperature": a.plan_temperature, "model": a.adapter or a.model}
                    f.write(json.dumps(ep) + "\n"); f.flush()
                    if not x["won"]: rel.write(json.dumps(to_release(ep)) + "\n"); rel.flush()
                    n += 1; wins += x["won"]
                    if n % 20 == 0: print(f"[{n}/{len(tasks) - len(done)}] success {wins}/{n} = {wins / n:.3f} {(time.time() - t0) / n:.2f}s/task (gen {tgen:.0f}s, score {tsc:.0f}s, {nsteps} steps)", flush=True)
                else: still.append(x)
            tsc += time.time() - ts; active = still
    print(f"DONE collect {wins}/{n} ({time.time() - t0:.0f}s; generation {tgen:.0f}s, scoring {tsc:.0f}s, {nsteps} steps)", flush=True)


def cmd_plan_report(a):
    """plan quality vs the oracle (diagnostic only): at t=0, does the student's 'Need total' equal the oracle's? and 'Next' == action taken."""
    env = TextCraftEnv()
    for path in a.files:
        E = L(ROOT / path); ok = 0; follows = steps = 0; okw = []; bad = []
        for e in E:
            env.reset(e["task"]); g = oracle_plans(env, e["task"], env.expert_actions())[0]
            need = lambda p: (re.search(r"Need total:\s*(.*?)\. Missing:", p or "") or [None, None])[1]
            strip = lambda s: re.sub(r" \([^)]*\)", "", s or "")
            good = strip(need(e["steps"][0]["plan"])) == strip(need(g)); ok += good; (okw if good else bad).append(e["won"])
            for s in e["steps"]: steps += 1; follows += plan_next(s["plan"]) == s["action"]
        print(f"== {path}: t=0 'Need total' equals the oracle's {ok}/{len(E)} = {ok / max(1, len(E)):.3f} (success {sum(okw)}/{len(okw)} when equal, {sum(bad)}/{len(bad)} "
              f"when not) | action == plan's Next on {follows}/{steps} = {follows / max(1, steps):.3f} steps")


