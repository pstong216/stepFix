"""TextCraft PLAN-AT-EVERY-STEP pipeline (option B, user-approved Oct 9; replaces the t=0-plan version in textcraft_plan.py, set aside).
STUDENT  at every step it first GENERATES a short plan (one line, fixed template), then chooses the action by scoring the admissible commands
         conditioned on task + history + this step's plan.  History = previous steps as (plan, action, observation), 10-step window; the task
         statement (crafting commands + goal) is always shown.
         Plan template (rendered from the oracle solver's state for the SFT demos):
           Have: <inventory or nothing>. Need total: <every base ingredient, total count (crafts x count when > 1 craft)>. Missing: <base items
           still to get or nothing>; <N> crafts left. Next: <action>.
demos    the same 100 TRAIN demos as student100, each step annotated with its oracle plan
sft      token-level SFT on the plan (plan prompt -> plan) + the same admissible-scoring SFT on the action (action prompt with the plan ->
         action); same hyper-parameters as student100
collect  batched: all active episodes generate their plans in one left-padded generate() call, then each scores its admissible commands;
         writes episodes with per-step plans + Who&When release rows for failures (plan = the step's reasoning)
fails    failures among the first N, K, release shards: query = complete task statement + HINT; reasoning = the student's per-step plan
variant  Model A agreement with the oracle reference first_waste for the no_observations / full variants on TRAINING failures -> choice
teacher  full-view teacher (task, whole trajectory incl. every plan, outcome, Model A diagnosis): (1) global analysis (total requirements, what
         went wrong, best action; 256 tokens), (2) corrected plan for the CURRENT step (plan template), (3) scores the admissible commands
         conditioned on that corrected plan
fix      for the env_top_margin-kept corrections: if the teacher's plan names a different Next action than the verified one, the plan is
         REGENERATED by the teacher conditioned on the verified action (Next forced); writes the training rows (plan SFT + one-hot action KL
         conditioned on the corrected plan) and the virtual episodes they read
replay   replay rows (fail_weighted by depth, textcraft_round.py replay_fw --carry) -> plan SFT row + action row per replayed step (own plans)
train    alfworld_opd_plus.cmd_train unchanged; rows with t < 0 are plan-generation SFT at state -(t+1)
"""
