def cmd_variant(a):
    from textcraft_evidence import refs
    from textcraft_round import merge
    D = ROOT / a.out_dir; eps = {e["id"]: e for e in L(ROOT / a.traj)}; ids = [r["id"] for r in L(D / "ids_fail.jsonl")]
    env = TextCraftEnv(); fw = {i: refs(env, eps[i])[0] for i in ids}; ok = [i for i in ids if fw[i] is not None]; res = {}
    print(f"first_waste reference: {len(ok)} failures, first_waste = 0 in {sum(fw[i] == 0 for i in ok)} (always-step-0 baseline exact {sum(fw[i] == 0 for i in ok) / max(1, len(ok)):.3f})")
    for v in a.variants:
        pred = merge(sorted(glob.glob(str(D / f"modelA_{v}" / "modelA_pred_s*.jsonl"))), lambda r: r["id"])
        miss = [i for i in ids if i not in pred]
        if miss: raise SystemExit(f"variant {v}: {len(miss)} predictions missing")
        th = {i: max(0, min(int(pred[i]["t_hat"]) if pred[i]["t_hat"] is not None else 0, len(eps[i]["steps"]) - 1)) for i in ids}
        pos = [i for i in ok if fw[i] > 0]
        res[v] = {"exact": sum(th[i] == fw[i] for i in ok) / max(1, len(ok)), "within1": sum(abs(th[i] - fw[i]) <= 1 for i in ok) / max(1, len(ok)),
                  "exact_fw_pos": sum(th[i] == fw[i] for i in pos) / max(1, len(pos)), "t0": sum(th[i] == 0 for i in ids) / len(ids), "n": len(ok)}
        print(f"variant {v}: exact agreement with first_waste {res[v]['exact']:.3f} ({sum(th[i] == fw[i] for i in ok)}/{len(ok)}), within 1 {res[v]['within1']:.3f}, "
              f"exact when first_waste > 0 {res[v]['exact_fw_pos']:.3f} ({sum(th[i] == fw[i] for i in pos)}/{len(pos)}), t0 share {res[v]['t0']:.2f}")
    best = max(res, key=lambda v: (res[v]["exact"], res[v]["within1"]))
    for f_ in glob.glob(str(D / "modelA_pred_s*.jsonl")): os.remove(f_)
    for f_ in sorted(glob.glob(str(D / f"modelA_{best}" / "modelA_pred_s*.jsonl"))): shutil.copy(f_, D / Path(f_).name)
    json.dump({"choice": best, "results": res}, open(D / "modelA_variant.json", "w"), indent=1)
    print(f"CHOSEN Model A variant: {best}")


# ----------------------------------------------------------------------------- teacher: analysis -> corrected plan -> scoring
def true_inventory(e, t):
    """environment inventory at step t (replay of the logged actions; what an 'inventory' action would return there)."""
    env = TextCraftEnv(); env.reset(e["task"])
    for s_ in e["steps"][:t]: env.step(s_["action"])
    return inv_str(env.inventory)


def set_have(plan, inv):
    """replace the plan's 'Have:' clause by the true inventory (Oct 9 design decision: the teacher hallucinated inventories from the hindsight
    future; the corrected plan is a training target at a known state, so its 'Have' is filled from the environment)."""
    if re.match(r"\s*Have:", plan or ""): return re.sub(r"^\s*Have:\s*.*?\.\s+(?=Need total:)", f"Have: {inv}. ", plan, count=1)
    return f"Have: {inv}. " + (plan or "")


