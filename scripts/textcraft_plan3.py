def L(p): return [json.loads(l) for l in open(p)] if Path(p).exists() else []


def inv_str(inv):
    return ", ".join(f"{n} {item_id_to_str(k)}" for k, n in sorted(inv.items())) or "nothing"


# ----------------------------------------------------------------------------- oracle plans
def oracle_plans(env, task, actions):
    """per-step plan text for an oracle action list (replayed from reset)."""
    env.reset(task); gets = collections.OrderedDict(); consumers = collections.defaultdict(list); groups = []
    for a in actions:
        if a.startswith("get "):
            _, n, it = a.split(" ", 2); gets[it] = gets.get(it, 0) + int(n)
        else:
            if groups and groups[-1][0] == a: groups[-1][1] += 1
            else: groups.append([a, 1])
    for cmd, n in groups:
        for x in cmd.split(" using ")[1].split(", "):
            c, it = x.split(" ", 1); consumers[it].append((n, int(c)))
    need = []
    for it, tot in gets.items():
        cs = consumers.get(it, []); s = sum(n * c for n, c in cs)
        need.append(f"{tot} {it}" + (f" ({' + '.join(f'{n}x{c}' for n, c in cs)})" if s == tot and (len(cs) > 1 or (cs and cs[0][0] > 1)) else ""))
    need = ", ".join(need) or "nothing"; plans = []
    for t, a in enumerate(actions):
        rem = collections.OrderedDict()
        for b in actions[t:]:
            if b.startswith("get "):
                _, n, it = b.split(" ", 2); rem[it] = rem.get(it, 0) + int(n)
        k = sum(1 for b in actions[t:] if b.startswith("craft "))
        plans.append(f"Have: {inv_str(env.inventory)}. Need total: {need}. Missing: {', '.join(f'{n} {it}' for it, n in rem.items()) or 'nothing'}; "
                     f"{k} crafts left. Next: {a}.")
        env.step(a)
    return plans


def plan_next(plan):
    m = re.search(r"Next:\s*(.+?)\.?\s*$", plan or ""); return m.group(1).strip() if m else None


# ----------------------------------------------------------------------------- prompts
def render(obs0, past, adm, plan=None, history=10):
    """past = [(plan, action, observation)]; plan=None -> plan-generation prompt, else the action prompt conditioned on `plan`."""
    lines = [obs0, ""]
    if len(past) > history: lines.append(f"(... {len(past) - history} earlier steps omitted)")
    for p, act, obs in past[-history:]: lines += [f"Plan: {p}", f"Action: {act}", f"Observation: {obs}"]
    lines.append("Admissible actions:"); lines += [f"- {x}" for x in adm]; lines.append("")
    lines += ([PLAN_ASK, "Plan:"] if plan is None else [f"Plan: {plan}", "Next action:"])
    return "\n".join(lines)


class _Step:
    def __init__(self, adm): self.admissible_commands = adm


class StepHistory:
    def __init__(self, obs0, past, adm, plan=None, history=10):
        self.obs0, self.past, self.adm, self.plan, self.H = obs0, list(past), list(adm), plan, history; self.steps = [_Step(self.adm)]
    def render_prompt(self, max_history_steps=None): return render(self.obs0, self.past, self.adm, self.plan, self.H)


def past_of(e, t): return [(s["plan"], s["action"], s["next_obs"]) for s in e["steps"][:t]]


def history_at(e, t, history=10):
    """t >= 0: action prompt at step t with that step's plan; t < 0: plan-generation prompt at step -(t+1)."""
    if t < 0:
        t = -t - 1; return StepHistory(e["initial_obs"], past_of(e, t), e["steps"][t]["admissible"], None, history)
    return StepHistory(e["initial_obs"], past_of(e, t), e["steps"][t]["admissible"], e["steps"][t]["plan"], history)


def policy_class():
    from error_attr.policy.alfworld_agent import LLMPolicy

    class PlanPolicy(LLMPolicy):
        def _build_chat_prompt(self, history):
            return self.tokenizer.apply_chat_template([{"role": "system", "content": PLAN_SYSTEM}, {"role": "user", "content": history.render_prompt()}],
                                                      tokenize=False, add_generation_prompt=True)
    return PlanPolicy


def load_policy(student, adapter, trainable=False, merge=False):
    import alfworld_opd_plus as O
    orig = getattr(O, "_orig_load_policy", O.load_policy)
    if merge and not trainable:
        import torch
        from transformers import AutoModelForCausalLM, AutoTokenizer
        from peft import PeftModel
        tok = AutoTokenizer.from_pretrained(student); tok.pad_token = tok.pad_token or tok.eos_token
        model = AutoModelForCausalLM.from_pretrained(student, dtype=torch.bfloat16, device_map={"": 0}).eval()
        if adapter: model = PeftModel.from_pretrained(model, adapter).merge_and_unload().eval()
    else:
        tok, model, _ = orig(student, adapter, trainable)
    return tok, model, policy_class()(model, tok)


def chat(tok, system, user):
    return tok.apply_chat_template([{"role": "system", "content": system}, {"role": "user", "content": user}], tokenize=False, add_generation_prompt=True)


def generate_batch(tok, model, prompts, max_new_tokens, temperature=0.0, one_line=True):
    """left-padded batched generation of chat-formatted prompts; returns the decoded continuations (first line if one_line)."""
    import torch
    side = tok.padding_side; tok.padding_side = "left"
    x = tok(prompts, return_tensors="pt", padding=True, add_special_tokens=False).to(model.device); tok.padding_side = side
    with torch.no_grad():
        o = model.generate(**x, max_new_tokens=max_new_tokens, do_sample=temperature > 0, temperature=max(temperature, 1e-5), top_p=1.0, pad_token_id=tok.pad_token_id)
    outs = tok.batch_decode(o[:, x.input_ids.shape[1]:], skip_special_tokens=True)
    return [(s.strip().split("\n")[0].strip() if one_line else " ".join(s.split())) for s in outs]


