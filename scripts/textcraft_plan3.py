def derivation(env, task):
    """oracle derivation of the base requirements from the SHOWN recipes, same computation as textcraft_evidence.req_tree (oracle recipe
    choice, batches rounded up per node): (derivation text, TOTAL string, total dict, check text)."""
    from textcraft_evidence import req_tree, default_member
    env.reset(task); nodes = req_tree(env); kids = {}
    for n in nodes:
        if n[1] is not None: kids.setdefault(n[1], []).append(n)
    label = lambda name, is_tag, leaf: item_id_to_str(name) if (leaf or not is_tag) else item_id_to_str(default_member(env, name))
    lines = []; total = collections.OrderedDict(); contrib = collections.defaultdict(list); prods = []
    for nid, par, name, is_tag, need in nodes:
        leaf = nid not in kids
        if leaf:
            if nid != 0: it = item_id_to_str(name); total[it] = total.get(it, 0) + need; contrib[it].append(need)
            continue
        conc = default_member(env, name) if is_tag else name; r = env._recipe_for(conc); k = r.output_item.count; c = _math.ceil(need / k)
        uses = []
        for ch in kids[nid]:
            cnt = ch[4] // c; uses.append(f"{c}x{cnt} = {ch[4]} {label(ch[2], ch[3], ch[0] not in kids)}"); prods.append(f"{c}x{cnt}={ch[4]}")
        lines.append(f"need {need} {label(name, is_tag, False)}: one craft makes {k}, crafts = ceil({need}/{k}) = {c}; uses " + ", ".join(uses))
    tot = ", ".join(f"{n} {it}" for it, n in total.items()) or "nothing"
    check = ("Check: " + "; ".join(prods) + "; " + "; ".join(f"{it} {' + '.join(map(str, contrib[it]))} = {total[it]}" for it in total) + "; ok")
    return "Derivation: " + ". ".join(lines) + ".", tot, dict(total), check


def need_dict(s):
    """'4 bamboo (2x2), 1 acacia logs' -> {'bamboo': 4, 'acacia logs': 1} (None if unparsable)."""
    s = re.sub(r"\s*\([^)]*\)", "", s or "").strip().rstrip(".")
    if s in ("", "nothing"): return {}
    out = {}
    try:
        for x in re.split(r",\s*|\s+\+\s+|;\s*", s):
            x = x.strip().lstrip("-").strip()
            if not x: continue
            n, it = x.split(" ", 1); out[it.strip()] = out.get(it.strip(), 0) + int(n)
    except Exception:
        return None
    return out


def plan_need(plan):
    m = re.search(r"Need total:\s*(.*?)\.\s*Missing:", plan or ""); return need_dict(m.group(1)) if m else None


def analysis_total(an):
    m = list(re.finditer(r"TOTAL:\s*(.+?)(?:\.\s|\.$|\n|\s+Check:|$)", an or ""))
    return (m[-1].group(1).strip(), need_dict(m[-1].group(1))) if m else (None, None)


def set_need(plan, tot):
    if "Need total:" in (plan or ""): return re.sub(r"Need total:\s*.*?\.\s*(?=Missing:)", f"Need total: {tot}. ", plan, count=1)
    return plan


def mask_need(plan): return re.sub(r"Need total:\s*.*?\.\s*(?=Missing:)", "Need total: [hidden]. ", plan or "", count=1)


