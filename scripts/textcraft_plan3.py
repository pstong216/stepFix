def wrong_total(env, task):
    """the root-cause error: recipe counts copied without multiplying by the number of crafts -> per-craft counts of the base ingredients;
    if that equals the true total, drop the last base ingredient (or subtract 1 for a single ingredient)."""
    from textcraft_evidence import req_tree
    der, tot, td, chk = derivation(env, task); env.reset(task); nodes = req_tree(env); kids = {n[1] for n in nodes if n[1] is not None}
    parent = {n[0]: n for n in nodes}; w = collections.OrderedDict()
    for nid, par, name, is_tag, need in nodes:
        if nid in kids or nid == 0: continue
        p_need = parent[par][4]; from textcraft_evidence import default_member
        pn = parent[par]; conc = default_member(env, pn[2]) if pn[3] else pn[2]; r = env._recipe_for(conc)
        c = _math.ceil(p_need / r.output_item.count); per = need // max(1, c); it = item_id_to_str(name); w[it] = w.get(it, 0) + per
    if dict(w) == td:
        if len(td) > 1: w = collections.OrderedDict(list(td.items())[:-1])
        else:
            it, n = list(td.items())[0]
            if n <= 1: return None
            w = {it: n - 1}
    return ", ".join(f"{n} {it}" for it, n in w.items())


def plans3(env, task, actions):
    """per-step plan3 text for the oracle actions: t=0 carries the derivation + TOTAL + check; later steps keep the TOTAL (plan2 template)."""
    der, tot, td, chk = derivation(env, task); base = oracle_plans(env, task, actions); out = []
    for t, p in enumerate(base):
        p = set_need(p, tot)
        out.append((f"{der} TOTAL: {tot}. {chk}. " + p) if t == 0 else p)
    return out, der, tot, chk


def recheck_plan(der, tot, chk, wrong, plan_t):
    return f"Re-check: the earlier Need total ({wrong}) is wrong. {der} TOTAL: {tot}. {chk}. " + plan_t


def cmd_demos3(a):
    """SFT pairs for the plan3 student: every demo step (plan target + action target) + verification augmentation: (a) the previous plans in
    the history carry a wrong Need total -> the target plan re-derives the correct one; (b) the same plus a failed craft ('Could not find
    enough items') inserted just before the step."""
    env = TextCraftEnv(); demos = [e for e in L(ROOT / a.src) if e["won"]][: a.n]; rng = random.Random(0); pairs = []; n_aug = collections.Counter()
    for e in demos:
        acts = [s["action"] for s in e["steps"]]; ps, der, tot, chk = plans3(env, e["task"], acts)
        e3 = json.loads(json.dumps(e))
        for s_, p in zip(e3["steps"], ps): s_["plan"] = p
        for t in range(len(acts)):
            pairs.append({"kind": "plan", "user": history_at(e3, -t - 1).render_prompt(), "target": ps[t]})
            pairs.append({"kind": "action", "user": history_at(e3, t).render_prompt(), "target": acts[t]})
        W = wrong_total(env, e["task"])
        if W is None or len(acts) < 2: continue
        for kind in ("a", "b"):
            t = rng.randrange(1, len(acts)); ew = json.loads(json.dumps(e3))
            for s_ in ew["steps"][:t]:
                s_["plan"] = set_need(s_["plan"].split(f"{chk}. ", 1)[-1] if s_["plan"].startswith("Derivation:") else s_["plan"], W)
