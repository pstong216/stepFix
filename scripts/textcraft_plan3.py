PLAN_SYSTEM = ("You are a crafting agent in a text-based Minecraft environment. You will be given the available crafting commands, a goal item "
               "and the history of your plans, actions and their results. When asked for the plan, write one short line: what you have, the total "
               "base ingredients the whole task needs (recipe counts multiplied by the number of crafts needed), what is still missing, and the "
               "next action. When asked for the next action, respond with the exact text of one admissible action and nothing else.")
PLAN_ASK = "Write the plan for this step."
HINT = ("Hint: in crafting tasks the decisive error is usually the earliest action that made success unreachable -- often a 'get' that fetched "
        "fewer items than the recipe chain requires (recipe counts must be multiplied by the number of crafts needed), a skipped ingredient, or a "
        "wrong recipe path (possibly already visible in the agent's reasoning). A later failed craft ('Could not find enough items') only reveals "
        "the shortage and is usually not the decisive error.")
